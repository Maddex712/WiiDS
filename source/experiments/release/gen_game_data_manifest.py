"""Write generated/data_sections_runtime.cpp: the WiiDS release replacement for data_sections_init.cpp.

The translator's data_sections_init.cpp + data_sections_init_blobs.S embed the game executable's
loaded sections in the native library. The runtime file written here embeds only each section's
name, guest address, size and SHA-256; WiiDSGameData::Load (runtime/src/wiids_game_data.cpp)
rebuilds the bytes from the player's own disc at startup and refuses anything that differs.

Usage: gen_game_data_manifest.py <runtime repo> <game>
  game: mkw | nsmbw | msmbwii
"""
import argparse
import hashlib
import re
from pathlib import Path

GAMES = {
    'mkw': ('Mario Kart Wii', 'Europe (PAL), game ID RMCP01, revision 0', 'None'),
    'nsmbw': ('New Super Mario Bros. Wii', 'USA, game ID SMNE01, revision 1', 'None'),
    'msmbwii': ('MSMBWii: Just a Little Adventure', 'New Super Mario Bros. Wii, USA, game ID SMNE01, revision 1', 'Msmbwii'),
}
SOURCES = {'StaticR': 'StaticRel', 'nsmbw_linked': 'NsmbwLinkedRels'}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('repo', type=Path)
    ap.add_argument('game', choices=sorted(GAMES))
    args = ap.parse_args()
    generated = args.repo / 'generated'
    init = (generated / 'data_sections_init.cpp').read_text(encoding='utf-8')
    entries = []
    for kind, name, address in re.findall(r'// (DOL|REL) section: (\S+) @ 0x([0-9A-Fa-f]+)', init):
        size = int(re.search(rf'constexpr size_t kSize_{re.escape(name)} = (\d+)u;', init).group(1))
        blob = (generated / 'data_sections_init_blobs' / f'{name}.bin').read_bytes()
        if len(blob) != size:
            raise SystemExit(f'{name}: blob is {len(blob)} bytes, initializer says {size}')
        source = 'DolSection' if kind == 'DOL' else SOURCES.get(name)
        if source is None:
            raise SystemExit(f'No runtime rebuild recipe for REL section {name}')
        entries.append((name, int(address, 16), size, hashlib.sha256(blob).hexdigest(), source))
    if not entries:
        raise SystemExit('No sections found in data_sections_init.cpp')
    title, disc, patch = GAMES[args.game]
    rows = '\n'.join(f'    {{"{n}", 0x{a:08X}u, {s}u, "{h}", WiiDSGameData::Source::{src}}},'
                     for n, a, s, h, src in entries)
    out = generated / 'data_sections_runtime.cpp'
    out.write_text(f'''// AUTO-GENERATED by experiments/release/gen_game_data_manifest.py - DO NOT EDIT
// WiiDS release data initializer for {title}. Holds section names, addresses, sizes and SHA-256
// pins only; no game bytes. The sections are rebuilt from the player's own disc at startup.
#include "wiids_game_data.h"

#include <iterator>

namespace {{
constexpr WiiDSGameData::Section kSections[] = {{
{rows}
}};
constexpr WiiDSGameData::Game kGame = {{"{title}", "{disc}", WiiDSGameData::Patch::{patch}}};
bool g_dataInitialized = false;
}} // namespace

extern "C" void InitializeDataSections() {{
    if (g_dataInitialized) return;
    g_dataInitialized = true;
    WiiDSGameData::Load(kGame, kSections, std::size(kSections));
}}

extern "C" bool IsDataSectionsInitialized() {{
    return g_dataInitialized;
}}
''', encoding='utf-8', newline='\n')
    print(f'{out}: {len(entries)} sections, {sum(e[2] for e in entries)} bytes rebuilt at startup')


if __name__ == '__main__':
    main()
